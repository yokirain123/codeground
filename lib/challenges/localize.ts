export function localizeChallenge(
  challenge: ChallengeDefinition,
  locale: Locale,
): ChallengeDefinition {
  if (locale === "en") {
    return challenge;
  }

  const copy = ukrainianChallengeCopy[challenge.slug];

  if (!copy) {
    return challenge;
  }

  return {
    ...challenge,
    ...copy,
    tags: [...copy.tags],
    requirements: [...copy.requirements],
  };
}
